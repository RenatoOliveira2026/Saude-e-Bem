def to_blocks(art):
    out = [{"type": "image",
            "url": f"https://images.unsplash.com/photo-{PHOTO[art['slug']]}?auto=format&fit=crop&w=1600&q=80",
            "alt": f"Foto ilustrativa: {art['title']} (Unsplash)"}]
    for b in art["blocks"]:
        k = b[0]
        if k == "p":
            if len(b) == 3 and b[2] == "html":
                out.append({"type": "paragraph", "text": "", "html": f"<p>{b[1]}</p>"})
            else:
                out.append({"type": "paragraph", "text": b[1]})
        elif k == "html":
            out.append({"type": "paragraph", "text": "", "html": f"<p>{b[1]}</p>"})
        elif k == "h2":
            out.append({"type": "heading", "level": 2, "text": b[1]})
        elif k == "h3":
            out.append({"type": "heading", "level": 3, "text": b[1]})
        elif k == "ul":
            out.append({"type": "list", "items": b[1]})
        elif k == "ol":
            out.append({"type": "list", "items": b[1], "ordered": True})
        elif k == "quote":
            out.append({"type": "blockquote", "text": b[1]})
        elif k == "faq":
            out.append({"type": "faq", "items": [{"question": q, "answer": a} for q, a in b[1]]})
        else:
            raise ValueError(k)
    return out
